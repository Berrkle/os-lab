def generate_agentic_plan(analysis_data: dict, out_dir: str) -> dict:
    os.makedirs(out_dir, exist_ok=True)
    pkg = analysis_data.get("package_info", {})
    pkg_name = pkg.get("package_name", "unknown")
    vulns = analysis_data.get("vulnerabilities", [])
    secrets = analysis_data.get("secrets", [])
    surface = analysis_data.get("attack_surface", {})

    print(f"[*] [Analyst Agent] Evaluating attack surface for: {pkg_name}")

    # Synthesize Attack Hypotheses
    hypotheses = []

    if pkg.get("flags", {}).get("debuggable"):
        hypotheses.append({
            "vector": "JDWP Debugger Attachment & Runtime Memory Inspection",
            "confidence": "HIGH",
            "priority": "P1",
            "action": f"adb forward tcp:8700 jdwp:<pid> && jdb -connect com.sun.jdi.SocketAttach:hostname=localhost,port=8700",
            "rationale": "App declares debuggable=true; debugger can halt execution and manipulate state."
        })

    if pkg.get("flags", {}).get("usesCleartextTraffic"):
        hypotheses.append({
            "vector": "MitM Cleartext HTTP Interception & Tampering",
            "confidence": "HIGH",
            "priority": "P1",
            "action": f"Route emulator traffic through mitmproxy (127.0.0.1:8080) and inspect unencrypted HTTP requests.",
            "rationale": "App explicitly permits cleartext HTTP, leaving API calls vulnerable to eavesdropping."
        })

    if secrets:
        hypotheses.append({
            "vector": "Exposed Hardcoded Credential Abuse",
            "confidence": "CRITICAL",
            "priority": "P0",
            "action": "Verify if hardcoded API keys/tokens are valid and have excessive cloud permissions.",
            "rationale": f"Discovered {len(secrets)} hardcoded secrets in APK assets and resources."
        })

    if surface.get("total_activities", 0) > 0:
        hypotheses.append({
            "vector": "Exported Activity Unauthorized Invocation & State Bypass",
            "confidence": "MEDIUM",
            "priority": "P2",
            "action": f"Execute automated IPC fuzzer against all exported activities.",
            "rationale": "Exported activities can be launched directly by any unprivileged app on device."
        })

    # Generate Tailored Frida Hooks via Exploit Agent
    print(f"[*] [Exploit Agent] Generating tailored Frida instrumentation scripts...")
    hook_files = generate_tailored_frida_hooks(pkg_name, vulns, out_dir)

    plan = {
        "target_package": pkg_name,
        "timestamp": datetime.now().isoformat(),
        "attack_hypotheses": hypotheses,
        "tailored_frida_hooks": hook_files,
        "recommended_dynamic_actions": [
            f"1. Connect ADB: adb connect 127.0.0.1:5555",
            f"2. Launch mitmweb: mitmweb -w artifacts/flows.mitm",
            f"3. Run tailored Frida hook: frida -U -f {pkg_name} -l {hook_files[0]} --no-pause",
            f"4. Monitor real-time logs: python scripts/logcat_monitor.py -p {pkg_name}",
            f"5. Fuzz exported IPC components: python scripts/ipc_fuzzer.py -p {pkg_name}"
        ]
    }

    # Save Plan JSON
    plan_json = os.path.join(out_dir, "agentic-plan.json")
    with open(plan_json, "w", encoding="utf-8") as f:
        json.dump(plan, f, indent=2)

    # Save Playbook Markdown
    playbook_md = os.path.join(out_dir, "agentic-playbook.md")
    with open(playbook_md, "w", encoding="utf-8") as f:
        f.write(f"# 🤖 Agentic Security Playbook: {pkg_name}\n\n")
        f.write(f"Generated by apk-lab Autonomous Security Engine at {plan['timestamp']}\n\n")

        f.write("## 🎯 Prioritized Attack Hypotheses (Analyst Agent)\n\n")
        f.write("| Priority | Vector | Confidence | Rationale |\n|---|---|---|---|\n")
        for h in hypotheses:
            f.write(f"| **{h['priority']}** | {h['vector']} | {h['confidence']} | {h['rationale']} |\n")
        f.write("\n")

        f.write("## 🛠️ Verification Execution Steps (Exploit Agent)\n\n")
        for step in plan["recommended_dynamic_actions"]:
            f.write(f"- `{step}`\n")
        f.write("\n")

        f.write("## 💉 Tailored Frida Scripts\n\n")
        for hf in hook_files:
            f.write(f"- [`{os.path.basename(hf)}`]({hf})\n")

    return plan


def main():
    parser = argparse.ArgumentParser(description="Agentic Mobile Security Engine")
    parser.add_argument("input", help="Path to APK or app-analysis.json")
    parser.add_argument("-o", "--out", help="Output directory")
    args = parser.parse_args()

    out_dir = args.out or os.path.join("artifacts", "agentic-plan")

    if args.input.endswith(".json") and os.path.isfile(args.input):
        with open(args.input, "r", encoding="utf-8") as f:
            data = json.load(f)
    elif args.input.endswith(".apk") and os.path.isfile(args.input):
        from app_analyzer import analyze_app
        data = analyze_app(args.input, out_dir)
    else:
        print(f"Error: Invalid input file: {args.input}")
        sys.exit(1)

    print("=== 🤖 Running Agentic Analyst & Exploit Engine ===")
    plan = generate_agentic_plan(data, out_dir)

    print(f"\nAgentic Plan Generated:")
    print(f"  Attack Hypotheses : {len(plan['attack_hypotheses'])}")
    print(f"  Tailored Hooks    : {len(plan['tailored_frida_hooks'])}")
    print(f"  Playbook saved to : {os.path.join(out_dir, 'agentic-playbook.md')}")


if __name__ == "__main__":
    main()
