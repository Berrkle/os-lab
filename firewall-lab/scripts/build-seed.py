#!/usr/bin/env python3
"""Compile every firewall-lab/companies/<slug>/company.json into the dashboard seed.

Writes dashboard/src/firewall/companies.generated.ts — a typed, committed module the
static dashboard imports. Run it after adding or editing a company, the same way you
run `npm run build` after changing the dashboard:

    python3 firewall-lab/scripts/build-seed.py

The generated file is checked in so the dashboard builds without this script; CI only
needs to confirm it is up to date.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COMPANIES = ROOT / "companies"
OUT = ROOT.parent / "dashboard" / "src" / "firewall" / "companies.generated.ts"

HEADER = """\
// AUTO-GENERATED by firewall-lab/scripts/build-seed.py — do not edit by hand.
// Source of truth: firewall-lab/companies/<slug>/company.json
// Regenerate: python3 firewall-lab/scripts/build-seed.py
import type { Company } from "./types";

export const COMPANIES: Company[] = """


def main() -> int:
    companies = []
    for folder in sorted(p for p in COMPANIES.iterdir() if p.is_dir()):
        manifest = folder / "company.json"
        if manifest.exists():
            with manifest.open(encoding="utf-8") as fh:
                companies.append(json.load(fh))
    body = json.dumps(companies, ensure_ascii=False, indent=2)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(f"{HEADER}{body};\n", encoding="utf-8")
    print(f"Wrote {len(companies)} companies -> {OUT.relative_to(ROOT.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
